Error init_error(ErrorCode code, const char* detail,
                 std::optional<std::int64_t> underlying = std::nullopt) {
  return Error{code, "relay_init", detail, underlying};
}

// Baseline relay.conf emitted when no configuration exists (the same values
// as the getting-started minimal sample, with password enrollment enabled).
std::string baseline_config_text(const RelayInitOptions& options) {
  std::string text;
  text += "# Generated by heyaki-relay --init; every key is documented in\n";
  text += "# docs/configuration.md.\n";
  text += "listen_address = " + options.listen_address.value_or("0.0.0.0") + "\n";
  text += "listen_port = " + std::to_string(options.listen_port.value_or(8443U)) + "\n";
  text += "tls_certificate_file = certs/relay.crt\n";
  text += "tls_private_key_file = certs/relay.key\n";
  text += "database_file = relay.sqlite\n";
  text += "enrollment_mode = password\n";
  text += "enrollment_default_tenant = " + options.enrollment_tenant + "\n";
  return text;
}

std::string hex_encode(const std::array<std::byte, 32U>& bytes) {
  static constexpr char digits[] = "0123456789abcdef";
  std::string output;
  output.reserve(bytes.size() * 2U);
  for (const auto byte : bytes) {
    const auto value = std::to_integer<unsigned char>(byte);
    output.push_back(digits[value >> 4U]);
    output.push_back(digits[value & 0x0fU]);
  }
  return output;
}

bool regular_file_exists(const std::filesystem::path& path) {
  std::error_code error;
  const bool exists = std::filesystem::is_regular_file(path, error);
  return !error && exists;
}

void restrict_owner_permissions(const std::filesystem::path& path) {
  std::error_code error;
  std::filesystem::permissions(path,
                               std::filesystem::perms::owner_read |
                                   std::filesystem::perms::owner_write,
                               error);
}

std::string_view advertised_host(const std::vector<std::string>& san_entries,
                                 const RelayInitOptions& options) {
  if (!options.listen_address.has_value() || options.listen_address == "0.0.0.0" ||
      options.listen_address == "::") {
    for (const auto& entry : san_entries) {
      if (entry != "localhost" && entry != "127.0.0.1" && entry != "::1") {
        return entry;
      }
    }
    return "localhost";
  }
  return *options.listen_address;
}

Result<std::array<std::byte, 32U>> certificate_digest(
    const std::filesystem::path& certificate_file) {
  // PEM I/O goes through OpenSSL BIO, never FILE*: on Windows the FILE*-based
  // PEM helpers require an OPENSSL_Applink table the app/test builds do not
  // provide and abort at runtime (OPENSSL_Uplink ... no OPENSSL_Applink).
#if defined(_WIN32)
  BIO* file = BIO_new_file(certificate_file.string().c_str(), "rb");
#else
  BIO* file = BIO_new_file(certificate_file.c_str(), "rb");
#endif
  if (file == nullptr) {
    return Result<std::array<std::byte, 32U>>::failure(
        init_error(ErrorCode::configuration, "relay_init_certificate_unreadable"));
  }
  X509* certificate = PEM_read_bio_X509(file, nullptr, nullptr, nullptr);
  BIO_free(file);
  if (certificate == nullptr) {
    return Result<std::array<std::byte, 32U>>::failure(
        init_error(ErrorCode::configuration, "relay_init_certificate_unreadable"));
  }
  std::array<std::byte, 32U> digest{};
  const int matched = X509_digest(certificate, EVP_sha256(),
                                  reinterpret_cast<unsigned char*>(digest.data()),
                                  nullptr);
  X509_free(certificate);
  if (matched != 1) {
    return Result<std::array<std::byte, 32U>>::failure(
        init_error(ErrorCode::configuration, "relay_init_certificate_digest_failed"));
  }
  return Result<std::array<std::byte, 32U>>::success(digest);
}

// Minimal path-key reader for the bootstrap order: init needs the configured
// certificate/key/database paths BEFORE load_relay_config_file can validate
// the configuration (which requires the certificate to exist). Returns the
// configured values resolved against the config directory, falling back to
// the baseline names when a key is absent.
struct RelayConfigPathKeys {
  std::filesystem::path tls_certificate_file{"certs/relay.crt"};
  std::filesystem::path tls_private_key_file{"certs/relay.key"};
  std::filesystem::path database_file{"relay.sqlite"};
};

Result<RelayConfigPathKeys> read_config_path_keys(const std::filesystem::path& config_file) {
  std::ifstream input{config_file, std::ios::binary};
  if (!input) {
    return Result<RelayConfigPathKeys>::failure(
        init_error(ErrorCode::configuration, "relay_init_config_unreadable", errno));
  }
  RelayConfigPathKeys keys;
  auto trim = [](std::string value) {
    const auto first = value.find_first_not_of(" \t");
    if (first == std::string::npos) {
      return std::string{};
    }
    const auto last = value.find_last_not_of(" \t");
    return value.substr(first, last - first + 1U);
  };
  std::string line;
  while (std::getline(input, line)) {
    const auto separator = line.find('=');
    if (separator == std::string::npos) {
      continue;
    }
    const auto key = trim(line.substr(0U, separator));
    const auto value = trim(line.substr(separator + 1U));
    if (key == "tls_certificate_file") {
      keys.tls_certificate_file = std::filesystem::path{value};
    } else if (key == "tls_private_key_file") {
      keys.tls_private_key_file = std::filesystem::path{value};
    } else if (key == "database_file" && value != ":memory:") {
      keys.database_file = std::filesystem::path{value};
    }
  }
  if (keys.tls_certificate_file.is_relative()) {
    keys.tls_certificate_file = config_file.parent_path() / keys.tls_certificate_file;
  }
  if (keys.tls_private_key_file.is_relative()) {
    keys.tls_private_key_file = config_file.parent_path() / keys.tls_private_key_file;
  }
  if (keys.database_file.is_relative()) {
    keys.database_file = config_file.parent_path() / keys.database_file;
  }
  return Result<RelayConfigPathKeys>::success(std::move(keys));
}

